#!/usr/bin/env python3
"""Fill token-free array/slice tier families; keep the existing native hooks."""
from pathlib import Path
import re
import subprocess
root = Path(__file__).resolve().parents[1]
ops = [('srgb_to_linear', False), ('linear_to_srgb', False),
       ('srgb_to_linear_extended', False), ('linear_to_srgb_extended', False),
       ('gamma_to_linear', False), ('linear_to_gamma', False)]
ops += [(name, True) for name in ['tf_srgb_to_linear', 'tf_linear_to_srgb',
    'bt709_to_linear', 'linear_to_bt709', 'pq_to_linear', 'linear_to_pq',
    'hlg_to_linear', 'linear_to_hlg']]
for width in [4, 8, 16]:
    source = root / f'src/target_features/x{width}.rs'
    text = source.read_text().split('// Portable tier completion')[0].rstrip() + '\n'
    existing = set(re.findall(r'fn (\w+)\(', text))
    extra = ['// Generated by scripts/generate_portable_target_features.py.\n']
    for tier in ['scalar', 'v3', 'v4', 'neon', 'wasm128']:
        for op, transfer in ops:
            gamma = op in ['gamma_to_linear', 'linear_to_gamma']
            arg = ', gamma: f32' if gamma else ''
            callarg = ', gamma' if gamma else ''
            name = f'{op}_{tier}'
            attrs = ('#[cfg(feature = "transfer")]\n' if transfer else '')
            attrs += '#[cfg(feature = "avx512")]\n' if tier == 'v4' else ''
            attrs += f'#[archmage::rite({tier})]\n'
            if name not in existing:
                if tier == 'scalar' and width == 4:
                    t = 'archmage::ScalarToken'
                    if op in ['srgb_to_linear', 'linear_to_srgb', 'gamma_to_linear', 'linear_to_gamma']:
                        body = f'crate::tokens::x4::{op}_core({t}, values{callarg})'
                    elif op.startswith('tf_'):
                        body = f'crate::tf::srgb::{op[3:]}_x4({t}, magetypes::simd::generic::f32x4::from_array_t({t}, values)).to_array()'
                    else:
                        body = f'values.map(crate::lanes::{op})'
                else:
                    child_tier = 'v3' if tier == 'v4' else tier
                    body = f'''let mut output = [0.0; {width}];
    for (src, dst) in values.as_chunks::<4>().0.iter().zip(output.as_chunks_mut::<4>().0) {{
        let converted = super::x4::{op}_{child_tier}(*src{callarg});
        dst.copy_from_slice(&converted);
    }}
    output'''
                extra += [f'/// Convert {width} values; see the module calling-context requirements.\n{attrs}pub fn {name}(values: [f32; {width}]{arg}) -> [f32; {width}] {{\n    {body}\n}}\n']
            slicename = f'{op}_slice_{tier}'
            if slicename not in existing:
                extra += [f'''/// Convert all values, including a final partial array.
{attrs}pub fn {slicename}(values: &mut [f32]{arg}) {{
    for chunk in values.chunks_mut({width}) {{
        let mut padded = [0.0; {width}];
        padded[..chunk.len()].copy_from_slice(chunk);
        let converted = {name}(padded{callarg});
        chunk.copy_from_slice(&converted[..chunk.len()]);
    }}
}}
''']
    source.write_text(text + f'\n// Portable tier completion\ninclude!("portable_x{width}.rs");\n')
    (root / f'src/target_features/portable_x{width}.rs').write_text('\n'.join(extra))

subprocess.run(["rustfmt", "--edition", "2024", *[str(root / f"src/target_features/portable_x{w}.rs") for w in [4, 8, 16]]], check=True)
